/** Body property of the single asset sent by Create */
const asset = (property: string) => `assets[0].${property}`;

const query = (property: string, value?: string) => ({
	send: value ? { type: 'query' as const, property, value } : { type: 'query' as const, property },
});

const csvFilter = (
	displayName: string,
	name: string,
	property: string,
	description: string,
): INodeProperties => ({
	displayName,
	name,
	type: 'string',
	default: '',
	description,
	routing: query(property, CSV_TO_LIST),
});

const multiFilter = (
	displayName: string,
	name: string,
	property: string,
	values: Array<string | [string, string]>,
): INodeProperties => ({
	displayName,
	name,
	type: 'multiOptions',
	options: enumOptions(values),
	default: [],
	routing: query(property),
});

const numberFilter = (
	displayName: string,
	name: string,
	property: string,
	description: string,
): INodeProperties => ({
	displayName,
	name,
	type: 'number',
	default: 0,
	description,
	routing: query(property),
});

const booleanFilter = (
	displayName: string,
	name: string,
	property: string,
	description: string,
): INodeProperties => ({
	displayName,
	name,
	type: 'boolean',
	default: false,
	description,
	routing: query(property),
});

